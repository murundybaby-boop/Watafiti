-- WATAFITI private document vault
-- Run once in Supabase Dashboard > SQL Editor.
-- This creates a PRIVATE bucket. It does not modify or delete existing articles or data.
insert into storage.buckets (id,name,public,file_size_limit,allowed_mime_types)
values (
 'watafiti-private-documents',
 'watafiti-private-documents',
 false,
 15728640,
 array[
  'application/pdf','image/jpeg','image/png','image/webp',
  'application/msword',
  'application/vnd.openxmlformats-officedocument.wordprocessingml.document',
  'application/vnd.ms-excel',
  'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet'
 ]
)
on conflict (id) do update set
 public=false,
 file_size_limit=15728640,
 allowed_mime_types=excluded.allowed_mime_types;

create table if not exists public.private_documents (
 id bigint generated by default as identity primary key,
 title text not null check (char_length(title) between 1 and 180),
 category text not null default 'Nyaraka nyingine' check (category in ('Vyeti','CV','Mikataba','Vitambulisho','Fedha','Nyaraka nyingine')),
 file_name text not null,
 storage_path text not null unique,
 mime_type text not null,
 file_size bigint not null check (file_size > 0 and file_size <= 15728640),
 created_by uuid not null references auth.users(id) on delete cascade,
 created_at timestamptz not null default now()
);
alter table public.private_documents enable row level security;
drop policy if exists "WATAFITI admins manage private document metadata" on public.private_documents;
create policy "WATAFITI admins manage private document metadata"
on public.private_documents for all to authenticated
using (exists (select 1 from public.admin_users where user_id=auth.uid()))
with check (exists (select 1 from public.admin_users where user_id=auth.uid()));
grant select,insert,update,delete on public.private_documents to authenticated;
grant usage,select on sequence public.private_documents_id_seq to authenticated;

drop policy if exists "WATAFITI admins access private documents" on storage.objects;
create policy "WATAFITI admins access private documents"
on storage.objects for all to authenticated
using (bucket_id='watafiti-private-documents' and exists (select 1 from public.admin_users where user_id=auth.uid()))
with check (bucket_id='watafiti-private-documents' and exists (select 1 from public.admin_users where user_id=auth.uid()));
