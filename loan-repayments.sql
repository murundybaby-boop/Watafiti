-- WATAFITI LOAN: manual repayment ledger.
-- Run in Supabase SQL Editor after loan-applications.sql.
-- This records payments only after the admin has independently confirmed receipt.
create table if not exists public.loan_repayments (
 id bigint generated by default as identity primary key,
 loan_application_id bigint not null references public.loan_applications(id) on delete restrict,
 amount integer not null check (amount between 1 and 100000000),
 paid_on date not null default current_date,
 reference text check (reference is null or char_length(reference) <= 120),
 notes text check (notes is null or char_length(notes) <= 500),
 created_by uuid not null default auth.uid(),
 created_at timestamptz not null default now()
);
alter table public.loan_repayments enable row level security;
revoke all on public.loan_repayments from anon, authenticated;
grant select, insert on public.loan_repayments to authenticated;
grant usage, select on sequence public.loan_repayments_id_seq to authenticated;
drop policy if exists "WATAFITI admins read loan repayments" on public.loan_repayments;
create policy "WATAFITI admins read loan repayments"
on public.loan_repayments for select to authenticated
using (exists (select 1 from public.admin_users where user_id=auth.uid()));
drop policy if exists "WATAFITI admins record loan repayments" on public.loan_repayments;
create policy "WATAFITI admins record loan repayments"
on public.loan_repayments for insert to authenticated
with check (
 exists (select 1 from public.admin_users where user_id=auth.uid())
 and created_by=auth.uid()
);
create index if not exists loan_repayments_loan_application_idx
on public.loan_repayments(loan_application_id, paid_on desc);
