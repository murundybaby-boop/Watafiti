-- WATAFITI Phase 3: video library.
-- Run in Supabase Dashboard > SQL Editor. This does not change or delete articles.
create table if not exists public.videos (
  id bigint generated by default as identity primary key,
  title text not null check (char_length(title) between 1 and 300),
  description text check (description is null or char_length(description) <= 3000),
  youtube_url text not null check (youtube_url ~* '^(https?://)(www[.]|m[.])?(youtube[.]com|youtu[.]be|youtube-nocookie[.]com)/'),
  category text check (category is null or char_length(category) <= 100),
  published boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists videos_publication_created_at_idx on public.videos (published, created_at desc);
alter table public.videos enable row level security;
revoke all on public.videos from anon, authenticated;
grant select on public.videos to anon, authenticated;
grant select, insert, update, delete on public.videos to authenticated;
drop policy if exists "Public can read published videos" on public.videos;
create policy "Public can read published videos" on public.videos for select to anon, authenticated using (published = true);
drop policy if exists "Admins can read all videos" on public.videos;
create policy "Admins can read all videos" on public.videos for select to authenticated using (exists (select 1 from public.admin_users where user_id = auth.uid()));
drop policy if exists "Admins can add videos" on public.videos;
create policy "Admins can add videos" on public.videos for insert to authenticated with check (exists (select 1 from public.admin_users where user_id = auth.uid()));
drop policy if exists "Admins can edit videos" on public.videos;
create policy "Admins can edit videos" on public.videos for update to authenticated using (exists (select 1 from public.admin_users where user_id = auth.uid())) with check (exists (select 1 from public.admin_users where user_id = auth.uid()));
drop policy if exists "Admins can delete videos" on public.videos;
create policy "Admins can delete videos" on public.videos for delete to authenticated using (exists (select 1 from public.admin_users where user_id = auth.uid()));
grant usage, select on sequence public.videos_id_seq to authenticated;
