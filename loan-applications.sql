-- WATAFITI LOAN applications. Run in Supabase Dashboard > SQL Editor.
create table if not exists public.loan_applications (
 id bigint generated by default as identity primary key,
 full_name text not null check (char_length(full_name) between 2 and 100),
 phone text not null check (char_length(phone) between 5 and 40),
 amount integer not null check (amount in (50000,100000,150000)),
 income_source text not null check (char_length(income_source) between 2 and 100),
 repayment_period text not null check (char_length(repayment_period) between 2 and 100),
 region text not null check (char_length(region) between 2 and 100),
 purpose text not null check (char_length(purpose) between 2 and 500),
 interest_rate numeric(5,2) not null default 15 check (interest_rate=15),
 status text not null default 'new' check (status in ('new','reviewing','approved','declined','answered')),
 admin_reply text check (admin_reply is null or char_length(admin_reply)<=2000),
 created_at timestamptz not null default now(),
 updated_at timestamptz not null default now()
);
alter table public.loan_applications enable row level security;
revoke all on public.loan_applications from anon, authenticated;
grant insert on public.loan_applications to anon;
grant usage, select on sequence public.loan_applications_id_seq to anon;
grant select, update on public.loan_applications to authenticated;
drop policy if exists "WATAFITI public submit loan application" on public.loan_applications;
create policy "WATAFITI public submit loan application" on public.loan_applications for insert to anon with check (status='new' and interest_rate=15);
drop policy if exists "WATAFITI admins read loan applications" on public.loan_applications;
create policy "WATAFITI admins read loan applications" on public.loan_applications for select to authenticated using (exists(select 1 from public.admin_users where user_id=auth.uid()));
drop policy if exists "WATAFITI admins update loan applications" on public.loan_applications;
create policy "WATAFITI admins update loan applications" on public.loan_applications for update to authenticated using (exists(select 1 from public.admin_users where user_id=auth.uid())) with check (exists(select 1 from public.admin_users where user_id=auth.uid()));
create index if not exists loan_applications_created_at_idx on public.loan_applications(created_at desc);
