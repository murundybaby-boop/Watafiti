create table if not exists public.reviews (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 100),
  rating integer not null check (rating between 1 and 5),
  content text not null check (char_length(content) between 1 and 2000),
  created_at timestamptz not null default now()
);
alter table public.reviews enable row level security;
grant select, insert on public.reviews to anon, authenticated;
drop policy if exists "Public can read reviews" on public.reviews;
create policy "Public can read reviews" on public.reviews for select to anon, authenticated using (true);
drop policy if exists "Visitors can submit reviews" on public.reviews;
create policy "Visitors can submit reviews" on public.reviews for insert to anon, authenticated
with check (char_length(name) between 1 and 100 and rating between 1 and 5 and char_length(content) between 1 and 2000);

create table if not exists public.visitor_events (
  id bigint generated by default as identity primary key,
  page text not null,
  created_at timestamptz not null default now()
);
alter table public.visitor_events enable row level security;
grant insert on public.visitor_events to anon, authenticated;
drop policy if exists "Visitors can record page visits" on public.visitor_events;
create policy "Visitors can record page visits" on public.visitor_events for insert to anon, authenticated
with check (char_length(page) between 1 and 500);

alter table public.articles enable row level security;
grant select on public.articles to anon, authenticated;
drop policy if exists "Public can read published articles" on public.articles;
create policy "Public can read published articles" on public.articles for select to anon, authenticated using (published = true);

-- Admin accounts must first be created in Supabase Authentication.
-- After a user signs up, add their Auth user UUID to this table using the SQL below.
create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);
alter table public.admin_users enable row level security;
revoke all on public.admin_users from anon, authenticated;
grant select on public.admin_users to authenticated;
drop policy if exists "Admins can see their own admin record" on public.admin_users;
create policy "Admins can see their own admin record" on public.admin_users
for select to authenticated using (user_id = auth.uid());

grant insert, update on public.articles to authenticated;
drop policy if exists "Admins can publish articles" on public.articles;
create policy "Admins can publish articles" on public.articles
for insert to authenticated with check (
  exists (select 1 from public.admin_users where user_id = auth.uid())
);
drop policy if exists "Admins can edit articles" on public.articles;
create policy "Admins can edit articles" on public.articles
for update to authenticated using (
  exists (select 1 from public.admin_users where user_id = auth.uid())
) with check (
  exists (select 1 from public.admin_users where user_id = auth.uid())
);

