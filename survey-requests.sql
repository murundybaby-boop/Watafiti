-- WATAFITI survey service requests
-- Run this script once in Supabase SQL Editor for persistent storage and admin review.
create table if not exists public.survey_requests (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 2 and 100),
  phone text not null check (char_length(phone) between 5 and 40),
  service_type text not null check (char_length(service_type) between 2 and 120),
  project_location text not null check (char_length(project_location) between 2 and 200),
  project_size text check (project_size is null or char_length(project_size) <= 120),
  requested_date date,
  details text check (details is null or char_length(details) <= 3000),
  status text not null default 'new' check (status in ('new','handled')),
  created_at timestamptz not null default now()
);
alter table public.survey_requests enable row level security;
revoke all on public.survey_requests from anon, authenticated;
grant insert on public.survey_requests to anon;
grant select, update, delete on public.survey_requests to authenticated;
drop policy if exists "WATAFITI public submit survey request" on public.survey_requests;
create policy "WATAFITI public submit survey request" on public.survey_requests
  for insert to anon with check (status = 'new');
drop policy if exists "WATAFITI admins read survey requests" on public.survey_requests;
create policy "WATAFITI admins read survey requests" on public.survey_requests
  for select to authenticated
  using (exists (select 1 from public.admin_users where user_id = auth.uid()));
drop policy if exists "WATAFITI admins update survey requests" on public.survey_requests;
create policy "WATAFITI admins update survey requests" on public.survey_requests
  for update to authenticated
  using (exists (select 1 from public.admin_users where user_id = auth.uid()))
  with check (exists (select 1 from public.admin_users where user_id = auth.uid()));
drop policy if exists "WATAFITI admins delete survey requests" on public.survey_requests;
create policy "WATAFITI admins delete survey requests" on public.survey_requests
  for delete to authenticated
  using (exists (select 1 from public.admin_users where user_id = auth.uid()));