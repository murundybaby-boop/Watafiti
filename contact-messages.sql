-- WATAFITI contact messages
create table if not exists public.contact_messages (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 2 and 100),
  email text not null check (char_length(email) between 5 and 254),
  phone text check (phone is null or char_length(phone) <= 40),
  subject text not null check (char_length(subject) between 2 and 160),
  message text not null check (char_length(message) between 5 and 5000),
  is_read boolean not null default false,
  created_at timestamptz not null default now()
);
alter table public.contact_messages enable row level security;
revoke all on public.contact_messages from anon, authenticated;
grant select, update, delete on public.contact_messages to authenticated;
drop policy if exists "WATAFITI admins read contact messages" on public.contact_messages;
create policy "WATAFITI admins read contact messages" on public.contact_messages
  for select to authenticated
  using (exists (select 1 from public.admin_users where user_id = auth.uid()));
drop policy if exists "WATAFITI admins update contact messages" on public.contact_messages;
create policy "WATAFITI admins update contact messages" on public.contact_messages
  for update to authenticated
  using (exists (select 1 from public.admin_users where user_id = auth.uid()))
  with check (exists (select 1 from public.admin_users where user_id = auth.uid()));
drop policy if exists "WATAFITI admins delete contact messages" on public.contact_messages;
create policy "WATAFITI admins delete contact messages" on public.contact_messages
  for delete to authenticated
  using (exists (select 1 from public.admin_users where user_id = auth.uid()));
